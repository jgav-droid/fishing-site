#!/usr/bin/env python3
"""Render RUN_RESULTS.md from the probe outputs (facts only, no verdict).

Reads out/dataset_probe.json, out/html_probe.json, out/probe_log.jsonl and,
if present, samples/quality.json.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT, SAMPLES = HERE / "out", HERE / "samples"


def load(p):
    return json.loads(p.read_text()) if p.exists() else None


def main():
    ds, html, q = load(OUT / "dataset_probe.json"), load(OUT / "html_probe.json"), load(SAMPLES / "quality.json")
    log = [json.loads(l) for l in (OUT / "probe_log.jsonl").read_text().splitlines()] if (OUT / "probe_log.jsonl").exists() else []
    L = ["# WDFW validation — run results (generated by report.py)", ""]

    L += ["## Requests", "", "| step | status / error | bytes | content-type | redirects | elapsed s | url |",
          "|---|---|---|---|---|---|---|"]
    for e in log:
        st = e["status"] if e["status"] is not None else f"{e['error_kind']}: {e['error']}"
        L.append(f"| {e['step']} | {st} | {e['bytes_read']} | {e['content_type'] or ''} | "
                 f"{len(e['redirects'])} | {e['elapsed_s']} | `{e['url']}` |")
    L.append("")

    if ds:
        L += ["## Dataset 6fex-3r7d", ""]
        if ds.get("fatal"):
            L += [f"**FATAL:** {ds['fatal']}", ""]
        else:
            md = ds["metadata"]
            L += [f"- name: {md['name']}", f"- attribution: {md['attribution']}",
                  f"- timestamps (UTC): `{json.dumps(md['timestamps_utc'])}`",
                  f"- row identifier column: {md['row_identifier_field']}",
                  f"- row count (count(*)): {ds.get('row_count')}",
                  f"- date fields: {ds.get('date_fields')}; ordering field: {ds.get('date_field')}",
                  f"- date coverage: `{json.dumps(ds.get('date_coverage'))}`",
                  f"- default page size (no $limit): {ds.get('default_page_rows')}",
                  f"- offset paging: {ds.get('offset_paging')}",
                  f"- CSV header matches schema: {ds.get('csv_header_matches_schema')}",
                  f"- incremental: `{json.dumps(ds.get('incremental'))}`", ""]
            schema = load(SAMPLES / "schema_6fex-3r7d.json")
            if schema:
                L += ["### Schema", "", "| fieldName | display name | type | non-null | smallest | largest |",
                      "|---|---|---|---|---|---|"]
                for c in schema["columns"]:
                    cc = c.get("cachedContents", {})
                    L.append(f"| `{c['fieldName']}` | {c['name']} | {c['dataTypeName']} | {cc.get('non_null', '')} | "
                             f"{cc.get('smallest', '')} | {cc.get('largest', '')} |")
                L.append("")
            L += ["### Bulk exports", ""]
            for k, v in ds.get("bulk", {}).items():
                L.append(f"- {k}: `{json.dumps({x: v.get(x) for x in v if x != 'preview'})}`")
            L += ["", "### Repeated reads", "", "| at | statuses | rowsUpdatedAt | column hash | count | rate-limit headers |",
                  "|---|---|---|---|---|---|"]
            for r in ds.get("repeats", []):
                L.append(f"| {r['at']} | {r['statuses']} | {r['rowsUpdatedAt']} | {r['column_hash']} | {r['count']} | {r['rate_limit_headers']} |")
            L.append("")

    if html:
        L += ["## HTML pages", ""]
        for name, p in html["pages"].items():
            L.append(f"### {name} — `{p['url']}`")
            for a in p["attempts"]:
                L.append(f"- {a['status'] or a['error_kind']} ua={a['user_agent']} {a['bytes_read']}B "
                         f"{a['content_type'] or ''} challenge={a['challenge_markers']} `{a['url']}`")
            for t in p.get("tables", []):
                L.append(f"- table header {t['header']}; rows seen {t['row_count_seen']}; "
                         f"dates {t['min_date']} .. {t['max_date']}; unparsed {t['unparsed_date_values']}")
            L.append("")
        L += ["Repeats: " + ", ".join(f"{r['page']}={r['status'] or r['error_kind']}" for r in html["repeats"]), ""]

    if q:
        L += ["## Normalization quality", "", "```json", json.dumps({k: v for k, v in q.items() if k != "future_dated_records"}, indent=2),
              "```", f"future-dated records in sample: {len(q['future_dated_records'])}", ""]

    (HERE / "RUN_RESULTS.md").write_text("\n".join(L))
    print("wrote RUN_RESULTS.md")


if __name__ == "__main__":
    main()
